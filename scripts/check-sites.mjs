import assert from "node:assert/strict";
import { readFile, readdir, stat } from "node:fs/promises";
import { createRequire } from "node:module";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const require = createRequire(import.meta.url);
const output = join(root, "out");
const html = await readFile(join(output, "index.html"), "utf8");
assert.match(html, /모아온/);
assert.match(html, /manifest\.webmanifest/);
assert.match(html, /apple-touch-icon/);
const manifest = JSON.parse(await readFile(join(output, "manifest.webmanifest"), "utf8"));
assert.equal(manifest.start_url, "/");
assert.equal(manifest.display, "standalone");
for (const icon of manifest.icons) assert.ok((await stat(join(output, icon.src))).size > 0);
assert.ok((await stat(join(output, "icon-180.png"))).size > 0);
const core = dirname(require.resolve("@ffmpeg/core"));
assert.deepEqual(await readFile(join(output, "ffmpeg/core.js")), await readFile(join(core, "ffmpeg-core.js")));
const parts = await Promise.all(["aa", "ab", "ac", "ad"].map(suffix => readFile(join(output, `ffmpeg/core.wasm.part-${suffix}`))));
assert.ok(parts.every(part => part.length > 0 && part.length <= 8 * 1024 * 1024));
const wasm = Buffer.concat(parts);
assert.deepEqual(wasm, await readFile(join(core, "ffmpeg-core.wasm")));
assert.ok(WebAssembly.validate(wasm), "FFmpeg core must be valid WebAssembly");
const files = await readdir(output, { recursive: true });
assert.ok(!files.some(file => file === "api" || file.startsWith("api/")), "Static output must not include an API");
let bundles = "";
for (const file of files.filter(file => file.endsWith(".js"))) bundles += await readFile(join(output, file), "utf8");
assert.match(bundles, /morrow-v1/);
assert.match(bundles, /core\.wasm\.part-/);
assert.ok(!bundles.includes("/api/export"), "Browser UI must not upload video to a server");
assert.match(await readFile(join(root, "app/api/export/route.ts"), "utf8"), /export async function POST/);
console.log("Static build passed: browser-only export, exact FFmpeg assets, localStorage key, install metadata, and preserved native API source.");
